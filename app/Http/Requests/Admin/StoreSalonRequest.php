<?php

namespace App\Http\Requests\Admin;

use App\Enums\UserRole;
use App\Support\PhoneNumber;
use Illuminate\Foundation\Http\FormRequest;

class StoreSalonRequest extends FormRequest
{
    /*
    |--------------------------------------------------------------------------
    | Authorization
    |--------------------------------------------------------------------------
    */

    public function authorize(): bool
    {
        return $this->user()?->hasRole(
                UserRole::SUPER_ADMIN
            ) === true;
    }


    /*
    |--------------------------------------------------------------------------
    | Prepare Data
    |--------------------------------------------------------------------------
    */

    protected function prepareForValidation(): void
    {
        $phone = trim(
            (string) $this->input('manager_phone', '')
        );

        if ($phone !== '') {
            try {
                $phone = PhoneNumber::normalize($phone);
            } catch (\Throwable) {
                // Let validation handle an invalid phone number.
            }
        }

        $this->merge([
            'manager_phone' => $phone,
        ]);
    }


    /*
    |--------------------------------------------------------------------------
    | Validation Rules
    |--------------------------------------------------------------------------
    */

    public function rules(): array
    {
        return [

            /*
            |--------------------------------------------------------------------------
            | Salon Information
            |--------------------------------------------------------------------------
            */

            'name' => [
                'required',
                'string',
                'min:2',
                'max:120',
            ],

            'description' => [
                'nullable',
                'string',
                'max:5000',
            ],


            /*
            |--------------------------------------------------------------------------
            | Salon Controller
            |--------------------------------------------------------------------------
            |
            | This person owns/controls the salon account.
            | Login is performed using manager_phone + OTP.
            |
            */

            'manager_name' => [
                'required',
                'string',
                'min:2',
                'max:120',
            ],

            'manager_phone' => [
                'required',
                'string',
                'regex:/^09\d{9}$/',
            ],


            /*
            |--------------------------------------------------------------------------
            | Salon Contact
            |--------------------------------------------------------------------------
            |
            | Salon phone is automatically taken from manager_phone
            | in SalonController.
            |
            */

            'email' => [
                'nullable',
                'email',
                'max:190',
            ],


            /*
            |--------------------------------------------------------------------------
            | Branding
            |--------------------------------------------------------------------------
            */

            'logo' => [
                'nullable',
                'image',
                'mimes:jpg,jpeg,png,webp',
                'max:4096',
            ],

            'cover' => [
                'nullable',
                'image',
                'mimes:jpg,jpeg,png,webp',
                'max:8192',
            ],

            'primary_color' => [
                'nullable',
                'regex:/^#[0-9A-Fa-f]{6}$/',
            ],

            'secondary_color' => [
                'nullable',
                'regex:/^#[0-9A-Fa-f]{6}$/',
            ],


            /*
            |--------------------------------------------------------------------------
            | Location
            |--------------------------------------------------------------------------
            */

            'province' => [
                'nullable',
                'string',
                'max:100',
            ],

            'city' => [
                'nullable',
                'string',
                'max:100',
            ],

            'district' => [
                'nullable',
                'string',
                'max:100',
            ],

            'address' => [
                'nullable',
                'string',
                'max:1000',
            ],

            'latitude' => [
                'nullable',
                'numeric',
                'between:-90,90',
            ],

            'longitude' => [
                'nullable',
                'numeric',
                'between:-180,180',
            ],


            /*
            |--------------------------------------------------------------------------
            | Status
            |--------------------------------------------------------------------------
            */

            'is_active' => [
                'nullable',
                'boolean',
            ],
        ];
    }


