<?php

namespace App\Http\Requests\Auth;

use Illuminate\Foundation\Http\FormRequest;

class RegisterVerifyRequest extends FormRequest
{
    /*
    |--------------------------------------------------------------------------
    | Authorization
    |--------------------------------------------------------------------------
    */

    public function authorize(): bool
    {
        return true;
    }


    /*
    |--------------------------------------------------------------------------
    | Prepare Input
    |--------------------------------------------------------------------------
    */

    protected function prepareForValidation(): void
    {
        $code = (string) $this->input(
            'code',
            ''
        );


        /*
        |--------------------------------------------------------------------------
        | Persian / Arabic digits -> English digits
        |--------------------------------------------------------------------------
        */

        $code = strtr(
            $code,
            [
                '۰' => '0',
                '۱' => '1',
                '۲' => '2',
                '۳' => '3',
                '۴' => '4',
                '۵' => '5',
                '۶' => '6',
                '۷' => '7',
                '۸' => '8',
                '۹' => '9',

                '٠' => '0',
                '١' => '1',
                '٢' => '2',
                '٣' => '3',
                '٤' => '4',
                '٥' => '5',
                '٦' => '6',
                '٧' => '7',
                '٨' => '8',
                '٩' => '9',
            ]
        );


        /*
        |--------------------------------------------------------------------------
        | Remove whitespace
        |--------------------------------------------------------------------------
        */

        $code = preg_replace(
            '/\s+/',
            '',
            $code
        );


        $this->merge([
            'code' => $code,
        ]);
    }


    /*
    |--------------------------------------------------------------------------
    | Rules
    |--------------------------------------------------------------------------
    */

    public function rules(): array
    {
        return [
            'code' => [
                'required',
                'string',
                'regex:/^\d{6}$/',
            ],
        ];
    }


    /*
    |--------------------------------------------------------------------------
    | Messages
    |--------------------------------------------------------------------------
    */

    public function messages(): array
    {
        return [
            'code.required' =>
                'کد تأیید را وارد کنید.',

            'code.string' =>
                'کد تأیید معتبر نیست.',

            'code.regex' =>
                'کد تأیید باید دقیقاً ۶ رقم باشد.',
        ];
    }
}
